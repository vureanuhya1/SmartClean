def generate_temporary_password(
    length=10
):

    alphabet = (
        "ABCDEFGHJKLMNPQRSTUVWXYZ"
        "abcdefghijkmnopqrstuvwxyz"
        "23456789@#"
    )


    while True:

        password = "".join(
            secrets.choice(alphabet)
            for _ in range(length)
        )


        if validate_password(password):

            return password


