@app.route(
    "/api/worker/complaints/<raw_id>/status",
    methods=["POST"]
)
@role_required("worker")
def api_worker_update(raw_id):

    complaint_id = parse_complaint_id(raw_id)

    data = (
        request.get_json(silent=True)
        or request.form
    )

    new_status = data.get("status")

    # Worker can ONLY move:
    # Assigned -> In Progress
    if complaint_id is None or new_status != "In Progress":
        return safe_json_error(
            "Workers can only change an Assigned complaint to In Progress.",
            400
        )

    conn = get_db_connection()

    cur = conn.cursor(
        dictionary=True
    )

    try:

        cur.execute(
            """
            SELECT
                c.status,
                ca.assignment_id

            FROM complaints c

            JOIN complaint_assignments ca
                ON ca.complaint_id = c.complaint_id

            WHERE
                c.complaint_id=%s
                AND ca.worker_id=%s

            LIMIT 1
            """,
            (
                complaint_id,
                session["user_id"]
            )
        )

        row = cur.fetchone()

        if not row:
            return safe_json_error(
                "Complaint is not assigned to you.",
                403
            )

        old_status = row["status"]

        # Only valid worker transition
        if old_status != "Assigned":
            return safe_json_error(
                f"Invalid status transition: {old_status} -> In Progress.",
                400
            )

        cur.execute(
            """
            UPDATE complaints
            SET status='In Progress'
            WHERE complaint_id=%s
            """,
            (complaint_id,)
        )

        cur.execute(
            """
            UPDATE complaint_assignments
            SET assignment_status='In Progress'
            WHERE
                complaint_id=%s
                AND worker_id=%s
            """,
            (
                complaint_id,
                session["user_id"]
            )
        )

        cur.execute(
            """
            INSERT INTO complaint_updates
            (
                complaint_id,
                updated_by,
                old_status,
                new_status,
                update_description
            )
            VALUES
            (
                %s,
                NULL,
                %s,
                'In Progress',
                %s
            )
            """,
            (
                complaint_id,
                old_status,
                "Status updated by assigned worker"
            )
        )

        conn.commit()

    except Exception:

        conn.rollback()
        raise

    finally:

        cur.close()
        conn.close()

    return jsonify(
        {
            "success": True,
            "message": "Complaint moved to In Progress."
        }
    )
    
