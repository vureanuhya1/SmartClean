@app.route(
    "/api/complaints/<raw_id>"
)
def api_track(raw_id):

    complaint_id = parse_complaint_id(
        raw_id
    )

    if complaint_id is None:

        return safe_json_error(
            "Invalid complaint ID.",
            400
        )

    conn = get_db_connection()

    cur = conn.cursor(
        dictionary=True
    )

    try:

        cur.execute(
            """
            SELECT
                c.*,
                ci.name AS citizen_name,
                ca.worker_id,
                w.name AS worker_name,

                (
                    SELECT MAX(updated_at)
                    FROM complaint_updates cu
                    WHERE cu.complaint_id =
                          c.complaint_id
                ) AS last_updated,

                rr.resolved_photo_path,
                rr.resolved_date,
                rr.request_status AS resolution_status,
                rr.decided_at AS resolution_decided_at

            FROM complaints c

            JOIN citizens ci
                ON ci.citizen_id =
                   c.citizen_id

            LEFT JOIN complaint_assignments ca
                ON ca.complaint_id =
                   c.complaint_id

            LEFT JOIN workers w
                ON w.worker_id =
                   ca.worker_id

            LEFT JOIN resolution_requests rr
                ON rr.request_id = (
                    SELECT MAX(rr2.request_id)
                    FROM resolution_requests rr2
                    WHERE rr2.complaint_id =
                          c.complaint_id
                      AND rr2.request_status =
                          'Approved'
                )

            WHERE c.complaint_id=%s
            """,
            (complaint_id,)
        )

        row = cur.fetchone()

    finally:

        cur.close()

        conn.close()

    if not row:

        return safe_json_error(
            "Complaint not found.",
            404
        )

    status = row["status"]

    if status == "Pending":

        display_status = "Submitted"

    elif status == "In Progress":

        display_status = "In Progress"

    elif status == "Assigned":

        display_status = "Assigned"

    elif status in (
        "Resolved",
        "Completed"
    ):

        display_status = "Completed"

    else:

        display_status = status

    description = (
        row["description"] or ""
    )

    if len(description) > 70:

        title = (
            description[:70]
            + "..."
        )

    else:

        title = description

    resolution_photo = (
        row["resolved_photo_path"]
        if row["resolution_status"] == "Approved"
        else None
    )

    resolution_date = (
        row["resolved_date"].strftime("%d %b %Y")
        if (
            row["resolution_status"] == "Approved"
            and row["resolved_date"]
        )
        else None
    )

    return jsonify(
        {
            "success": True,

            "id":
                complaint_display_id(
                    complaint_id
                ),

            "title":
                title,

            "ward":
                f"Ward {row['ward_number']}",

            "filed":
                (
                    row["complaint_date"]
                    .strftime("%d %b %Y")
                    if row["complaint_date"]
                    else "-"
                ),

            "status":
                display_status,

            "location":
                row["street_number"],

            "worker":
                (
                    row["worker_name"]
                    or "Not yet assigned"
                ),

            "category":
                row["issue_type"],
	    "photo_path":
 		   row["photo_path"],
            "updated":
                (
                    row["last_updated"]
                    .strftime(
                        "%d %b %Y %H:%M"
                    )
                    if row["last_updated"]
                    else
                    "Not updated yet"
                ),

            "resolution_photo":
                resolution_photo,

            "resolution_date":
                resolution_date,

            "resolution_status":
                (
                    row["resolution_status"]
                    if row["resolution_status"]
                    else None
                )
        }
    )

