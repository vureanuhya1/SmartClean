def send_email(
    to_email,
    subject,
    body
):

    if not SMTP_EMAIL or not SMTP_PASSWORD:

        raise RuntimeError(
            "SMTP is not configured. "
            "Add SMTP_EMAIL and SMTP_PASSWORD to .env"
        )


    message = EmailMessage()

    message["Subject"] = subject

    message["From"] = (
        f"{MAIL_FROM_NAME} <{SMTP_EMAIL}>"
    )

    message["To"] = to_email

    message.set_content(body)


    with smtplib.SMTP(
        SMTP_HOST,
        SMTP_PORT,
        timeout=20
    ) as smtp:

        smtp.ehlo()

        smtp.starttls()

        smtp.ehlo()

        smtp.login(
            SMTP_EMAIL,
            SMTP_PASSWORD
        )

        smtp.send_message(
            message
        )


