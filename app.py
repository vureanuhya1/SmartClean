def role_required(role):

    def decorator(function):

        @wraps(function)

        def wrapper(
            *args,
            **kwargs
        ):

            if session.get("role") != role:

                return redirect(
                    url_for(
                        f"{role}_login"
                    )
                )


            return function(
                *args,
                **kwargs
            )


        return wrapper

    return decorator


