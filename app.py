@app.route(
    "/api/complaints/<raw_id>"
)
def api_track(raw_id):

    complaint_id = parse_complaint_id(
        raw_id
    )


    if complaint_id is None:

        return safe_json_error(
            "Invalid complaint ID.",
            400
        )


    conn = get_db_connection()

    cur = conn.cursor(
        dictionary=True
    )


    try:

        cur.execute(
            """
            SELECT
                c.*,
                ci.name AS citizen_name,
                ca.worker_id,
                w.name AS worker_name,

                (
                    SELECT MAX(updated_at)
                    FROM complaint_updates cu
                    WHERE cu.complaint_id =
                          c.complaint_id
                ) AS last_updated

            FROM complaints c

            JOIN citizens ci
                ON ci.citizen_id =
                   c.citizen_id

            LEFT JOIN complaint_assignments ca
                ON ca.complaint_id =
                   c.complaint_id

            LEFT JOIN workers w
                ON w.worker_id =
                   ca.worker_id

            WHERE c.complaint_id=%s
            """,
            (complaint_id,)
        )


        row = cur.fetchone()


    finally:

        cur.close()

        conn.close()


    if not row:

        return safe_json_error(
            "Complaint not found.",
            404
        )


    status = row["status"]


    if status == "Pending":

        display_status = "Submitted"


    elif status == "In Progress":

        display_status = "In Progress"


    elif status == "Assigned":

        display_status = "Assigned"


    elif status in (
        "Resolved",
        "Completed"
    ):

        display_status = "Completed"


    else:

        display_status = status


    description = (
        row["description"] or ""
    )


    if len(description) > 70:

        title = (
            description[:70]
            + "..."
        )

    else:

        title = description


    return jsonify(
        {
            "success": True,

            "id":
                complaint_display_id(
                    complaint_id
                ),

            "title":
                title,

            "ward":
                f"Ward {row['ward_number']}",

            "filed":
                (
                    row["complaint_date"]
                    .strftime("%d %b %Y")
                    if row["complaint_date"]
                    else "-"
                ),

            "status":
                display_status,

            "location":
                row["street_number"],

            "worker":
                (
                    row["worker_name"]
                    or "Not yet assigned"
                ),

            "category":
                row["issue_type"],

            "updated":
                (
                    row["last_updated"]
                    .strftime(
                        "%d %b %Y %H:%M"
                    )
                    if row["last_updated"]
                    else
                    "Not updated yet"
                )
        }
    )


