def send_email(
    to_email,
    subject,
    body
):

    if not MAILJET_API_KEY or not MAILJET_SECRET_KEY:

        raise RuntimeError(
            "Mailjet is not configured. "
            "Add MAILJET_API_KEY and MAILJET_SECRET_KEY "
            "to Railway Variables."
        )


    import base64
    import json
    import urllib.request


    url = "https://api.mailjet.com/v3.1/send"


    credentials = (
        f"{MAILJET_API_KEY}:{MAILJET_SECRET_KEY}"
    ).encode("utf-8")


    auth = base64.b64encode(
        credentials
    ).decode("ascii")


    html_body = (
        body
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\n", "<br>")
    )


    payload = {
        "Messages": [
            {
                "From": {
                    "Email": MAILJET_FROM_EMAIL,
                    "Name": MAIL_FROM_NAME
                },

                "To": [
                    {
                        "Email": to_email
                    }
                ],

                "Subject": subject,

                "TextPart": body,

                "HTMLPart": html_body
            }
        ]
    }


    request_data = json.dumps(
        payload
    ).encode("utf-8")


    req = urllib.request.Request(
        url,
        data=request_data,
        method="POST"
    )


    req.add_header(
        "Authorization",
        f"Basic {auth}"
    )

    req.add_header(
        "Content-Type",
        "application/json"
    )


    try:

        with urllib.request.urlopen(
            req,
            timeout=20
        ) as response:

            response_body = response.read().decode(
                "utf-8"
            )

            if response.status < 200 or response.status >= 300:

                raise RuntimeError(
                    f"Mailjet returned HTTP "
                    f"{response.status}: "
                    f"{response_body}"
                )

            return json.loads(
                response_body
            )

    except Exception as e:

        raise RuntimeError(
            f"Mailjet email sending failed: {e}"
        )

