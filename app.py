@app.route(
    "/api/worker/complaints/<raw_id>/status",
    methods=["POST"]
)
@role_required("worker")
def api_worker_update(raw_id):

    complaint_id = parse_complaint_id(
        raw_id
    )


    data = (
        request.get_json(
            silent=True
        )
        or request.form
    )


    new_status = data.get(
        "status"
    )


    allowed_statuses = {
        "In Progress",
        "Resolved"
    }

    if complaint_id is None or new_status not in allowed_statuses:
        return safe_json_error(
            "Invalid complaint or status. Use In Progress or Resolved.",
            400
        )


    conn = get_db_connection()

    cur = conn.cursor(
        dictionary=True
    )


    try:

        cur.execute(
            """
            SELECT
                c.status

            FROM complaints c

            JOIN complaint_assignments ca
                ON ca.complaint_id =
                   c.complaint_id

            WHERE
                c.complaint_id=%s
                AND ca.worker_id=%s
            """,
            (
                complaint_id,
                session["user_id"]
            )
        )


        row = cur.fetchone()


        if not row:

            return safe_json_error(
                "Complaint is not assigned to you.",
                403
            )


        old_status = row["status"]

        # Enforce the Worker workflow:
        # Assigned -> In Progress -> Resolved
        valid_transition = (
            (old_status == "Assigned" and new_status == "In Progress")
            or (old_status == "In Progress" and new_status == "Resolved")
        )

        if not valid_transition:
            return safe_json_error(
                f"Invalid status transition: {old_status} -> {new_status}. "
                "Worker flow is Assigned -> In Progress -> Resolved.",
                400
            )

        cur.execute(
            """
            UPDATE complaints
            SET status=%s
            WHERE complaint_id=%s
            """,
            (new_status, complaint_id)
        )

        cur.execute(
            """
            UPDATE complaint_assignments
            SET assignment_status=%s
            WHERE
                complaint_id=%s
                AND worker_id=%s
            """,
            (
                new_status,
                complaint_id,
                session["user_id"]
            )
        )

        cur.execute(
            """
            INSERT INTO complaint_updates
            (
                complaint_id,
                updated_by,
                old_status,
                new_status,
                update_description
            )
            VALUES
            (
                %s,
                NULL,
                %s,
                %s,
                %s
            )
            """,
            (
                complaint_id,
                old_status,
                new_status,
                "Status updated by assigned worker"
            )
        )

        conn.commit()


    finally:

        cur.close()

        conn.close()


    return jsonify(
        {
            "success": True
        }
    )


