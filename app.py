# ============================================================

def update_profile(
    role,
    json_response=False
):

    # --------------------------------------------------------
    # CHECK ROLE
    # --------------------------------------------------------

    if role not in ROLE_TABLES:

        if json_response:

            return safe_json_error(
                "Invalid user role.",
                400
            )


        return redirect(
            url_for("login")
        )


    # --------------------------------------------------------
    # GET CURRENT USER
    # --------------------------------------------------------

    user = current_user()


    if not user:

        if json_response:

            return safe_json_error(
                "User session expired. Please log in again.",
                401
            )


        return redirect(
            url_for(
                f"{role}_login"
            )
        )


    cfg = ROLE_TABLES[role]


    # --------------------------------------------------------
    # READ JSON OR FORM DATA
    # --------------------------------------------------------

    if request.is_json:

        data = (
            request.get_json(
                silent=True
            )
            or {}
        )

    else:

        data = request.form


    # --------------------------------------------------------
    # READ VALUES
    # --------------------------------------------------------

    name = str(
        data.get(
            "name",
            ""
        )
    ).strip()


    email = str(
        data.get(
            "email",
            ""
        )
    ).strip()


    phone = str(
        data.get(
            "phone",
            ""
        )
    ).strip()


    address = str(
        data.get(
            "address",
            ""
        )
    ).strip()


    # --------------------------------------------------------
    # NAME VALIDATION
    # --------------------------------------------------------

    if not name:

        if json_response:

            return safe_json_error(
                "Name cannot be empty.",
                400
            )


        return render_template(
            f"{role}-profile.html",
            user=current_user(),
            error="Name cannot be empty."
        ), 400


    # --------------------------------------------------------
    # EMAIL VALIDATION
    # --------------------------------------------------------

    if not email:

        if json_response:

            return safe_json_error(
                "Email cannot be empty.",
                400
            )


        return render_template(
            f"{role}-profile.html",
            user=current_user(),
            error="Email cannot be empty."
        ), 400


    email_pattern = (
        r"^[^@\s]+@[^@\s]+\.[^@\s]+$"
    )


    if not re.match(
        email_pattern,
        email
    ):

        if json_response:

            return safe_json_error(
                "Please enter a valid email address.",
                400
            )


        return render_template(
            f"{role}-profile.html",
            user=current_user(),
            error=(
                "Please enter a valid email address."
            )
        ), 400


    # --------------------------------------------------------
    # PHONE VALIDATION
    # --------------------------------------------------------

    if phone:

        if not phone.isdigit():

            if json_response:

                return safe_json_error(
                    "Phone number must contain only digits.",
                    400
                )


            return render_template(
                f"{role}-profile.html",
                user=current_user(),
                error=(
                    "Phone number must contain only digits."
                )
            ), 400


        if len(phone) != 10:

            if json_response:

                return safe_json_error(
                    "Phone number must contain 10 digits.",
                    400
                )


            return render_template(
                f"{role}-profile.html",
                user=current_user(),
                error=(
                    "Phone number must contain 10 digits."
                )
            ), 400


    # --------------------------------------------------------
    # BUILD UPDATE FIELDS
    # --------------------------------------------------------

    fields = []

    values = []


    # NAME

    fields.append(
        "name=%s"
    )

    values.append(
        name
    )


    # EMAIL

    fields.append(
        "email=%s"
    )

    values.append(
        email
    )


    # PHONE

    fields.append(
        "phone=%s"
    )

    values.append(
        phone
    )


    # --------------------------------------------------------
    # CITIZEN-SPECIFIC FIELDS
    # --------------------------------------------------------

    if role == "citizen":

        if "address" in data:

            fields.append(
                "address=%s"
            )

            values.append(
                address
            )


        if "ward_number" in data:

            ward_value = data.get(
                "ward_number"
            )


            try:

                ward_number = int(
                    ward_value
                )


                fields.append(
                    "ward_number=%s"
                )

                values.append(
                    ward_number
                )


            except (
                TypeError,
                ValueError
            ):

                pass


    # --------------------------------------------------------
    # WORKER-SPECIFIC FIELDS
    # --------------------------------------------------------

    elif role == "worker":

        if "address" in data:

            fields.append(
                "address=%s"
            )

            values.append(
                address
            )


        if "status" in data:

            status = str(
                data.get(
                    "status"
                )
            ).strip()


            if status in {
                "Available",
                "Busy",
                "Unavailable"
            }:

                fields.append(
                    "status=%s"
                )

                values.append(
                    status
                )


    # --------------------------------------------------------
    # ADMIN-SPECIFIC FIELDS
    # --------------------------------------------------------

    elif role == "admin":

        if "address" in data:
            fields.append("address=%s")
            values.append(address)


    # --------------------------------------------------------
    # USER ID FOR WHERE CLAUSE
    # --------------------------------------------------------

    values.append(
        user[cfg["id"]]
    )


    # --------------------------------------------------------
    # DATABASE UPDATE
    # --------------------------------------------------------

    conn = None

    cur = None


    try:

        conn = get_db_connection()

        cur = conn.cursor()


        query = f"""
            UPDATE {cfg["table"]}
            SET {", ".join(fields)}
            WHERE {cfg["id"]}=%s
        """


        cur.execute(
            query,
            tuple(values)
        )


        conn.commit()


    except mysql.connector.Error as e:

        if conn:

            conn.rollback()


        message = getattr(
            e,
            "msg",
            str(e)
        )


        if (
            "Duplicate entry"
            in message
            and "email"
            in message.lower()
        ):

            message = (
                "This email address is already "
                "registered with another account."
            )


        elif (
            "Duplicate entry"
            in message
            and "phone"
            in message.lower()
        ):

            message = (
                "This phone number is already "
                "registered with another account."
            )


        if json_response:

            return safe_json_error(
                message,
                400
            )


        return render_template(
            f"{role}-profile.html",
            user=current_user(),
            error=message
        ), 400


    finally:

        if cur:

            cur.close()


        if conn:

            conn.close()


    # --------------------------------------------------------
    # GET UPDATED USER FROM DATABASE
    # --------------------------------------------------------

    updated_user = current_user()


    # --------------------------------------------------------
    # JSON RESPONSE
    # --------------------------------------------------------

    if json_response:

        return jsonify(
            {
                "success": True,
                "message":
                    "Profile updated successfully!",
                "user":
                    updated_user
            }
        )


    # --------------------------------------------------------
    # NORMAL FORM RESPONSE
    # --------------------------------------------------------

    return redirect(
        url_for(
            f"{role}_profile"
        )
    )


