@app.route(
    "/report-issue",
    methods=["GET", "POST"]
)
def report_issue():
    if session.get("role") != "citizen":
        return redirect(
            url_for("citizen_login", next="/report-issue")
        )

    user = current_user()

    if not user:
        session.clear()
        return redirect(
            url_for("citizen_login", next="/report-issue")
        )

    if request.method == "GET":
        return render_template(
            "report-issue.html",
            user=user,
            form_data={}
        )

    category = request.form.get("category", "").strip()
    issue_type = CATEGORY_MAP.get(category, category)

    street_name = request.form.get("street_name", "").strip()
    ward_number = request.form.get("ward_number", "").strip()
    description = request.form.get("description", "").strip()

    form_data = {
        "name": request.form.get("name", "").strip(),
        "email": request.form.get("email", "").strip(),
        "category": category,
        "street_name": street_name,
        "ward_number": ward_number,
        "description": description
    }

    # Validate required complaint fields
    if not issue_type or not street_name or not ward_number or not description:
        return render_template(
            "report-issue.html",
            user=user,
            form_data=form_data,
            error="Please fill all required fields."
        ), 400

    # Complaint photo is mandatory
    photo = request.files.get("photo")

    if not photo or not photo.filename:
        return render_template(
            "report-issue.html",
            user=user,
            form_data=form_data,
            error="Complaint photo is required."
        ), 400

    # Validate photo type
    ext = Path(photo.filename).suffix.lower()

    if ext not in {".jpg", ".jpeg", ".png"}:
        return render_template(
            "report-issue.html",
            user=user,
            form_data=form_data,
            error="Only JPG and PNG images are allowed."
        ), 400

    # Save complaint photo
    filename = f"{secrets.token_hex(12)}{ext}"

    photo.save(
        Path(app.config["UPLOAD_FOLDER"]) / filename
    )

    photo_path = f"uploads/{filename}"

    conn = get_db_connection()
    cur = conn.cursor()

    try:
        cur.execute(
            """
            INSERT INTO complaints
            (
                citizen_id,
                issue_type,
                ward_number,
                street_number,
                description,
                photo_path,
                status
            )
            VALUES (%s, %s, %s, %s, %s, %s, 'Pending')
            """,
            (
                user["citizen_id"],
                issue_type,
                int(ward_number),
                street_name,
                description,
                photo_path
            )
        )

        complaint_id = cur.lastrowid
        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()
    cid = complaint_display_id(complaint_id)

    return render_template(
        "report-issue.html",
        user=user,
        form_data={},
        success=True,
        complaint_id=cid,
        success_message=f"Complaint {cid} submitted successfully."
    )
