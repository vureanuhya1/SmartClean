def validate_password(password):

    if not password:
        return False


    if len(password) < 6:
        return False


    if not any(
        character.isupper()
        for character in password
    ):
        return False


    if not any(
        character.isdigit()
        for character in password
    ):
        return False


    return True


def password_matches(
    stored,
    supplied
):

    if not stored:
        return False


    if stored.startswith(
        (
            "pbkdf2:",
            "scrypt:"
        )
    ):

        return check_password_hash(
            stored,
            supplied
        )


    return secrets.compare_digest(
        str(stored),
        str(supplied)
    )


