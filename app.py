        # This Month
        date_condition = """
            c.complaint_date >=
                DATE_FORMAT(
                    CURDATE(),
                    '%Y-%m-01'
                )
            AND
            c.complaint_date <
                DATE_ADD(
                    DATE_FORMAT(
                        CURDATE(),
                        '%Y-%m-01'
                    ),
                    INTERVAL 1 MONTH
                )
        """


